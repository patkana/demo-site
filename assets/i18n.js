      const value = table[key];
      const text = (lang === 'bg' || value === undefined) ? ORIG.get(el) : value;
      if (text === undefined) continue;
      if (el.dataset.i18nAttr) el.setAttribute(attrOf(el), text);
      else if (el.dataset.i18nAlt) el.setAttribute('alt', text);
      else if (el.dataset.i18nPh) el.setAttribute('placeholder', text);
